create table if not exists public.georgia_sales_tax_rates (
  id bigint generated by default as identity primary key,
  jurisdiction_code text not null,
  jurisdiction_name text not null,
  rate_percent numeric(6,3) not null check (rate_percent >= 0 and rate_percent <= 100),
  effective_from date not null,
  effective_to date not null,
  rate_source text not null,
  source_url text not null,
  source_updated_at date not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint georgia_sales_tax_rates_period_check check (effective_to >= effective_from),
  unique (jurisdiction_code, effective_from, effective_to)
);

create table if not exists public.georgia_tax_destination_rules (
  id bigint generated by default as identity primary key,
  postal_code text not null check (postal_code ~ '^[0-9]{5}$'),
  city_normalized text not null,
  jurisdiction_code text not null,
  jurisdiction_name text not null,
  active boolean not null default true,
  priority integer not null default 100,
  rule_source text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (postal_code, city_normalized, jurisdiction_code)
);

