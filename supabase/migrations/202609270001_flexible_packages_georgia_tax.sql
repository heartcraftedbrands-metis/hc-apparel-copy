create or replace function public.get_georgia_checkout_tax_rate(
  destination_zip text,
  destination_city text,
  calculation_date date default current_date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  matched_rule public.georgia_tax_destination_rules%rowtype;
  matched_rate public.georgia_sales_tax_rates%rowtype;
begin
  select * into matched_rule
  from public.georgia_tax_destination_rules
  where active = true
    and postal_code = left(regexp_replace(coalesce(destination_zip, ''), '[^0-9]', '', 'g'), 5)
    and city_normalized = upper(trim(coalesce(destination_city, '')))
  order by priority asc, id asc
  limit 1;

  if matched_rule.id is null then
    return jsonb_build_object(
      'ok', false,
      'code', 'GA_TAX_JURISDICTION_UNRESOLVED',
      'message', 'Georgia destination county or Atlanta jurisdiction could not be resolved from the delivery address.'
    );
  end if;

  select * into matched_rate
  from public.georgia_sales_tax_rates
  where jurisdiction_code = matched_rule.jurisdiction_code
    and calculation_date between effective_from and effective_to
  order by effective_from desc
  limit 1;

  if matched_rate.id is null then
    return jsonb_build_object(
      'ok', false,
      'code', 'GA_TAX_RATE_EXPIRED',
      'message', 'No effective Georgia sales-tax rate is configured for this destination and date.',
      'jurisdiction_code', matched_rule.jurisdiction_code,
      'jurisdiction_name', matched_rule.jurisdiction_name
    );
  end if;

  return jsonb_build_object(
    'ok', true,
    'method', 'destination_based',
    'jurisdiction_code', matched_rate.jurisdiction_code,
    'jurisdiction_name', matched_rate.jurisdiction_name,
    'rate_percent', matched_rate.rate_percent,
    'effective_from', matched_rate.effective_from,
    'effective_to', matched_rate.effective_to,
    'rate_source', matched_rate.rate_source,
    'source_url', matched_rate.source_url,
    'last_tax_rate_update', matched_rate.source_updated_at
  );
end;
$$;

revoke all on function public.get_georgia_checkout_tax_rate(text, text, date) from public, anon, authenticated;
grant execute on function public.get_georgia_checkout_tax_rate(text, text, date) to service_role;

